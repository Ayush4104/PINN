"""
Physics-Informed Neural Network (PINN) for the 1D transient (unsteady)
heat conduction equation with NO internal heat generation:

    du/dt = alpha * d2u/dx2 ,   x in [0, L], t in [0, T]

Boundary conditions (Dirichlet, editable below):
    u(0, t) = T_left
    u(L, t) = T_right

Initial condition:
    u(x, 0) = f(x)

The network u_theta(x, t) is trained so that it simultaneously satisfies:
  1) the PDE residual  r = du/dt - alpha*d2u/dx2  = 0   at collocation points
  2) the initial condition
  3) the boundary conditions

An analytical reference solution (Fourier series for a rod with fixed end
temperatures) is used to check accuracy.
"""

import numpy as np
import torch
import torch.nn as nn
import matplotlib.pyplot as plt
import os

# Save plots into current working directory (Colab: /content)
SAVE_DIR = os.getcwd()

torch.manual_seed(0)
np.random.seed(0)

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# ----------------------------------------------------------------------
# 1. Problem definition
# ----------------------------------------------------------------------
L = 1.0          # rod length
T_final = 1.0    # total simulated time
alpha = 0.05     # thermal diffusivity

T_left = 0.0     # boundary temperature at x=0
T_right = 0.0    # boundary temperature at x=L


def initial_condition(x):
    """u(x, 0) = f(x). Here: a sine pulse (analytical solution known)."""
    return torch.sin(np.pi * x / L)


def analytical_solution(x, t, n_terms=1):
    """
    Exact solution for u(x,0)=sin(pi x/L), u(0,t)=u(L,t)=0:
        u(x,t) = exp(-alpha*(pi/L)^2 * t) * sin(pi x / L)
    (Only the first Fourier mode is needed since IC is a pure sine.)
    """
    return np.exp(-alpha * (np.pi / L) ** 2 * t) * np.sin(np.pi * x / L)


# ----------------------------------------------------------------------
# 2. Neural network definition
# ----------------------------------------------------------------------
class PINN(nn.Module):
    def __init__(self, layers):
        super().__init__()
        modules = []
        for i in range(len(layers) - 2):
            modules.append(nn.Linear(layers[i], layers[i + 1]))
            modules.append(nn.Tanh())
        modules.append(nn.Linear(layers[-2], layers[-1]))
        self.net = nn.Sequential(*modules)

        # Xavier init helps tanh networks converge better
        for m in self.net:
            if isinstance(m, nn.Linear):
                nn.init.xavier_normal_(m.weight)
                nn.init.zeros_(m.bias)

    def forward(self, x, t):
        xt = torch.cat([x, t], dim=1)
        return self.net(xt)


layers = [2, 40, 40, 40, 40, 1]   # input (x,t) -> hidden -> output u
model = PINN(layers).to(device)

# ----------------------------------------------------------------------
# 3. Sampling points
# ----------------------------------------------------------------------
N_f = 10000   # collocation (interior) points for PDE residual
N_0 = 200     # initial-condition points
N_b = 200     # boundary points (per boundary)


def to_tensor(arr):
    return torch.tensor(arr, dtype=torch.float32, device=device, requires_grad=True)


# Interior collocation points (x, t) sampled uniformly at random
x_f = np.random.uniform(0, L, (N_f, 1))
t_f = np.random.uniform(0, T_final, (N_f, 1))
x_f_t = to_tensor(x_f)
t_f_t = to_tensor(t_f)

# Initial condition points: t = 0
x_0 = np.random.uniform(0, L, (N_0, 1))
t_0 = np.zeros((N_0, 1))
u_0 = initial_condition(torch.tensor(x_0, dtype=torch.float32)).numpy()
x_0_t = to_tensor(x_0)
t_0_t = to_tensor(t_0)
u_0_t = torch.tensor(u_0, dtype=torch.float32, device=device)

# Boundary points: x = 0 and x = L
t_b = np.random.uniform(0, T_final, (N_b, 1))
x_b_left = np.zeros((N_b, 1))
x_b_right = np.full((N_b, 1), L)

x_b_left_t = to_tensor(x_b_left)
x_b_right_t = to_tensor(x_b_right)
t_b_t = to_tensor(t_b)

u_b_left_t = torch.full((N_b, 1), T_left, dtype=torch.float32, device=device)
u_b_right_t = torch.full((N_b, 1), T_right, dtype=torch.float32, device=device)


# ----------------------------------------------------------------------
# 4. PDE residual via automatic differentiation
# ----------------------------------------------------------------------
def pde_residual(model, x, t):
    u = model(x, t)

    u_t = torch.autograd.grad(
        u, t, grad_outputs=torch.ones_like(u), create_graph=True
    )[0]
    u_x = torch.autograd.grad(
        u, x, grad_outputs=torch.ones_like(u), create_graph=True
    )[0]
    u_xx = torch.autograd.grad(
        u_x, x, grad_outputs=torch.ones_like(u_x), create_graph=True
    )[0]

    residual = u_t - alpha * u_xx
    return residual


# ----------------------------------------------------------------------
# 5. Loss function
# ----------------------------------------------------------------------
mse = nn.MSELoss()


def compute_loss():
    # PDE residual loss
    res = pde_residual(model, x_f_t, t_f_t)
    loss_pde = mse(res, torch.zeros_like(res))

    # Initial condition loss
    u0_pred = model(x_0_t, t_0_t)
    loss_ic = mse(u0_pred, u_0_t)

    # Boundary condition losses
    ub_left_pred = model(x_b_left_t, t_b_t)
    ub_right_pred = model(x_b_right_t, t_b_t)
    loss_bc = mse(ub_left_pred, u_b_left_t) + mse(ub_right_pred, u_b_right_t)

    loss = loss_pde + 10.0 * loss_ic + 10.0 * loss_bc
    return loss, loss_pde, loss_ic, loss_bc


# ----------------------------------------------------------------------
# 6. Training: Adam followed by L-BFGS fine-tuning
# ----------------------------------------------------------------------
optimizer_adam = torch.optim.Adam(model.parameters(), lr=1e-3)

epochs_adam = 5000
history = []

print("Training with Adam...")
for epoch in range(epochs_adam):
    optimizer_adam.zero_grad()
    loss, loss_pde, loss_ic, loss_bc = compute_loss()
    loss.backward()
    optimizer_adam.step()

    if epoch % 500 == 0:
        history.append(loss.item())
        print(
            f"Epoch {epoch:5d} | total {loss.item():.3e} | "
            f"pde {loss_pde.item():.3e} | ic {loss_ic.item():.3e} | "
            f"bc {loss_bc.item():.3e}"
        )

print("\nFine-tuning with L-BFGS...")
optimizer_lbfgs = torch.optim.LBFGS(
    model.parameters(),
    max_iter=2000,
    tolerance_grad=1e-9,
    tolerance_change=1e-12,
    history_size=50,
    line_search_fn="strong_wolfe",
)


def closure():
    optimizer_lbfgs.zero_grad()
    loss, _, _, _ = compute_loss()
    loss.backward()
    return loss


optimizer_lbfgs.step(closure)
final_loss, final_pde, final_ic, final_bc = compute_loss()
print(
    f"Final  | total {final_loss.item():.3e} | pde {final_pde.item():.3e} | "
    f"ic {final_ic.item():.3e} | bc {final_bc.item():.3e}"
)

# ----------------------------------------------------------------------
# 7. Evaluation against the analytical solution
# ----------------------------------------------------------------------
model.eval()

n_x, n_t = 200, 200
x_grid = np.linspace(0, L, n_x)
t_grid = np.linspace(0, T_final, n_t)
X, Tm = np.meshgrid(x_grid, t_grid)

x_flat = X.reshape(-1, 1)
t_flat = Tm.reshape(-1, 1)

with torch.no_grad():
    x_eval = torch.tensor(x_flat, dtype=torch.float32, device=device)
    t_eval = torch.tensor(t_flat, dtype=torch.float32, device=device)
    u_pred = model(x_eval, t_eval).cpu().numpy().reshape(n_t, n_x)

u_exact = analytical_solution(X, Tm)
error = np.abs(u_pred - u_exact)
l2_error = np.linalg.norm(u_pred - u_exact) / np.linalg.norm(u_exact)
print(f"\nRelative L2 error vs analytical solution: {l2_error:.4%}")

# ----------------------------------------------------------------------
# 8. Plots
# ----------------------------------------------------------------------
fig, axs = plt.subplots(1, 3, figsize=(16, 4.5))

im0 = axs[0].pcolormesh(X, Tm, u_pred, shading="auto", cmap="inferno")
axs[0].set_title("PINN prediction u(x,t)")
axs[0].set_xlabel("x")
axs[0].set_ylabel("t")
fig.colorbar(im0, ax=axs[0])

im1 = axs[1].pcolormesh(X, Tm, u_exact, shading="auto", cmap="inferno")
axs[1].set_title("Analytical solution")
axs[1].set_xlabel("x")
axs[1].set_ylabel("t")
fig.colorbar(im1, ax=axs[1])


im2 = axs[2].pcolormesh(X, Tm, error, shading="auto", cmap="viridis")
axs[2].set_title(f"Absolute error (rel. L2={l2_error:.2%})")
axs[2].set_xlabel("x")
axs[2].set_ylabel("t")
fig.colorbar(im2, ax=axs[2])

plt.tight_layout()
plt.savefig(os.path.join(SAVE_DIR, "pinn_heat_1d_field.png"), dpi=150)
plt.show()

# Snapshot comparison at a few times
fig2, ax2 = plt.subplots(figsize=(7, 5))
for t_snap in [0.0, 0.1, 0.3, 0.6, 1.0]:
    idx = (np.abs(t_grid - t_snap)).argmin()
    ax2.plot(x_grid, u_exact[idx], "k-", linewidth=2, alpha=0.6,
              label="analytical" if t_snap == 0.0 else None)
    ax2.plot(x_grid, u_pred[idx], "--", label=f"PINN, t={t_grid[idx]:.2f}")

ax2.set_xlabel("x")
ax2.set_ylabel("u(x,t)")
ax2.set_title("Temperature profiles at selected times")
ax2.legend()
plt.tight_layout()
plt.savefig(os.path.join(SAVE_DIR, "pinn_heat_1d_snapshots.png"), dpi=150)
plt.show()

print("\nSaved plots:")
print(" - pinn_heat_1d_field.png       (2D field comparison)")
print(" - pinn_heat_1d_snapshots.png   (1D profile snapshots)")